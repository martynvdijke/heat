// OIDCClaims is the verified ID token payload Heat cares about.
type OIDCClaims struct {
	Sub               string   `json:"sub"`
	Email             string   `json:"email"`
	EmailVerified     bool     `json:"email_verified"`
	Groups            []string `json:"groups"`
	Name              string   `json:"name"`
	PreferredUsername string   `json:"preferred_username"`
}

// Cached OIDC provider setup, re-initialized when config changes.
var (
	oidcMu       sync.Mutex
	oidcProvider *oidc.Provider
	oidcVerifier *oidc.IDTokenVerifier
	oidcOAuth2   *oauth2.Config
	oidcIssuer   string
	oidcClientID string
)

func oidcSetup(ctx context.Context, h *Handler) (*oidc.Provider, *oidc.IDTokenVerifier, *oauth2.Config, error) {
	cfg := h.S.OIDC
	oidcMu.Lock()
	defer oidcMu.Unlock()
	if oidcProvider != nil && oidcIssuer == cfg.IssuerURL && oidcClientID == cfg.ClientID {
		return oidcProvider, oidcVerifier, oidcOAuth2, nil
	}
	provider, err := oidc.NewProvider(ctx, cfg.IssuerURL)
	if err != nil {
		return nil, nil, nil, err
	}
	oidcProvider = provider
	oidcVerifier = provider.Verifier(&oidc.Config{ClientID: cfg.ClientID})
	oidcOAuth2 = &oauth2.Config{
		ClientID:     cfg.ClientID,
		ClientSecret: cfg.ClientSecret,
		RedirectURL:  cfg.RedirectURL,
		Endpoint:     provider.Endpoint(),
		Scopes:       cfg.Scopes,
	}
	oidcIssuer = cfg.IssuerURL
	oidcClientID = cfg.ClientID
	return oidcProvider, oidcVerifier, oidcOAuth2, nil
}

func oidcRandom(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		return ""
	}
	return base64.RawURLEncoding.EncodeToString(b)
}

func oidcTempCookie(c *gin.Context, name, value string, secure bool) {
	http.SetCookie(c.Writer, &http.Cookie{
		Name:     name,
		Value:    value,
		Path:     "/",
		MaxAge:   600,
		HttpOnly: true,
		Secure:   secure,
		SameSite: http.SameSiteLaxMode,
	})
}

func oidcClearCookie(c *gin.Context, name string, secure bool) {
	http.SetCookie(c.Writer, &http.Cookie{
		Name:     name,
		Value:    "",
		Path:     "/",
		MaxAge:   -1,
		HttpOnly: true,
		Secure:   secure,
		SameSite: http.SameSiteLaxMode,
	})
}

func oidcInGroups(groups []string, want string) bool {
	for _, g := range groups {
		if g == want {
			return true
		}
	}
	return false
}

// validOIDCDeviceCode accepts the opaque polling code generated by the Android
// app. Codes are random tokens, never user-controlled display strings.
func validOIDCDeviceCode(code string) bool {
	if len(code) < 16 || len(code) > 128 {
		return false
	}
	for _, r := range code {
		switch {
		case r >= 'a' && r <= 'z':
		case r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9':
		case r == '-' || r == '_':
		default:
			return false
		}
	}
	return true
}

// oidcMobileDevice returns the device code carried through the browser flow,
// or "" for the regular web login.
func oidcMobileDevice(c *gin.Context) string {
	cookie, err := c.Request.Cookie("oidc_device")
	if err != nil {
		return ""
	}
	if !validOIDCDeviceCode(cookie.Value) {
		return ""
	}
	return cookie.Value
}

// oidcAbort finishes a native login with an error the app can display instead
// of leaving it polling until the pending entry expires.
func (h *Handler) oidcAbort(c *gin.Context, device string, status int, message string) {
	if device != "" {
		h.S.PutOIDCPendingLoginError(device, message)
		oidcClearCookie(c, "oidc_device", h.S.SecureCookies)
	}
	c.AbortWithStatusJSON(status, gin.H{"error": message})
}

// oidcBaseURL resolves the public origin the browser should open. The
// configured redirect URL is authoritative behind a reverse proxy.
func oidcBaseURL(c *gin.Context, h *Handler) string {
	if h.S.OIDC.RedirectURL != "" {
		if u, err := url.Parse(h.S.OIDC.RedirectURL); err == nil && u.Scheme != "" && u.Host != "" {
			prefix := strings.TrimSuffix(u.Path, "/api/auth/oidc/callback")
			return u.Scheme + "://" + u.Host + strings.TrimSuffix(prefix, "/")
		}
	}
	scheme := "http"
	if c.Request.TLS != nil {
		scheme = "https"
	}
	if proto := c.GetHeader("X-Forwarded-Proto"); proto != "" {
		scheme = strings.TrimSpace(strings.Split(proto, ",")[0])
	}
	return scheme + "://" + c.Request.Host
}

// @Summary OIDC provider status
// @Description Returns whether OIDC login is enabled
// @Tags Auth
// @Produce json
// @Success 200 {object} map[string]bool
// @Router /api/auth/oidc/config [get]
func (h *Handler) HandleOIDCConfig(c *gin.Context) {
	c.JSON(http.StatusOK, gin.H{"enabled": h.S.OIDC.Enabled})
}

// @Summary Start OIDC login
// @Description Redirect to Authelia authorize with PKCE S256 + state/nonce cookies
// @Tags Auth
// @Success 302 {string} string "Redirect to IdP"
// @Router /api/auth/oidc/login [get]
func (h *Handler) HandleOIDCLogin(c *gin.Context) {
	if !h.S.OIDC.Enabled {
		c.AbortWithStatusJSON(http.StatusNotFound, gin.H{"error": "OIDC disabled"})
		return
	}
	device := c.Query("device")
	if device != "" {
		if !validOIDCDeviceCode(device) {
			c.AbortWithStatusJSON(http.StatusBadRequest, gin.H{"error": "invalid device code"})
			return
		}
		oidcTempCookie(c, "oidc_device", device, h.S.SecureCookies)
	}
	_, _, oauth2Cfg, err := oidcSetup(c.Request.Context(), h)
	if err != nil {
		log.Printf("[OIDC] provider discovery failed: %v", err)
		h.oidcAbort(c, device, http.StatusBadGateway, "OIDC provider unavailable")
		return
	}
	state := oidcRandom(32)
	nonce := oidcRandom(32)
	verifier := oauth2.GenerateVerifier()
	if state == "" || nonce == "" || verifier == "" {
		h.oidcAbort(c, device, http.StatusInternalServerError, "failed to generate OIDC parameters")
		return
	}
	oidcTempCookie(c, "oidc_state", state, h.S.SecureCookies)
	oidcTempCookie(c, "oidc_nonce", nonce, h.S.SecureCookies)
	oidcTempCookie(c, "oidc_pkce", verifier, h.S.SecureCookies)
	c.Redirect(http.StatusFound, oauth2Cfg.AuthCodeURL(state, oidc.Nonce(nonce), oauth2.S256ChallengeOption(verifier)))
}

// @Summary Start OIDC login from a native app
// @Description Creates a device code and browser URL for the app to poll after the browser flow
// @Tags Auth
// @Produce json
// @Success 200 {object} map[string]string
// @Router /api/auth/oidc/mobile/start [post]
func (h *Handler) HandleOIDCMobileStart(c *gin.Context) {
	if !h.S.OIDC.Enabled {
		c.AbortWithStatusJSON(http.StatusNotFound, gin.H{"error": "OIDC disabled"})
		return
	}
	device := oidcRandom(32)
	if device == "" {
		c.AbortWithStatusJSON(http.StatusInternalServerError, gin.H{"error": "failed to generate device code"})
		return
	}
	authURL := oidcBaseURL(c, h) + "/api/auth/oidc/login?device=" + url.QueryEscape(device)
	c.JSON(http.StatusOK, gin.H{"device_code": device, "auth_url": authURL})
}

// @Summary Poll a native OIDC login
// @Description Returns pending until the browser callback completes, then the session exactly once
// @Tags Auth
// @Produce json
// @Success 200 {object} map[string]string
// @Router /api/auth/oidc/mobile/status [get]
func (h *Handler) HandleOIDCMobileStatus(c *gin.Context) {
	if !h.S.OIDC.Enabled {
		c.AbortWithStatusJSON(http.StatusNotFound, gin.H{"error": "OIDC disabled"})
		return
	}
	// The successful response carries a session token; never let a proxy or
	// browser cache it.
	c.Header("Cache-Control", "no-store")
	device := c.Query("device")
	if !validOIDCDeviceCode(device) {
		c.AbortWithStatusJSON(http.StatusBadRequest, gin.H{"error": "invalid device code"})
		return
	}
	pending, ok := h.S.TakeOIDCPendingLogin(device)
	if !ok {
		c.JSON(http.StatusOK, gin.H{"status": "pending"})
		return
	}
	if pending.Error != "" {
		c.JSON(http.StatusOK, gin.H{"status": "error", "error": pending.Error})
		return
	}
	c.JSON(http.StatusOK, gin.H{"status": "ok", "session": pending.SessionID})
}

